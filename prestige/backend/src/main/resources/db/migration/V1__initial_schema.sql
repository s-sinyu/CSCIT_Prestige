-- Prestige renovation platform: initial schema (PostgreSQL 16).
-- All timestamps are stored in UTC (timestamptz). Enum values are stored as text with CHECK constraints.

CREATE TABLE users (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email           varchar(255) NOT NULL,
    password_hash   varchar(100) NOT NULL,
    full_name       varchar(150) NOT NULL,
    phone           varchar(30),
    role            varchar(30)  NOT NULL CHECK (role IN ('CUSTOMER','INTERIOR_DESIGNER','PLATFORM_MANAGEMENT','USER_ADMIN')),
    status          varchar(20)  NOT NULL CHECK (status IN ('ACTIVE','SUSPENDED')),
    deleted         boolean      NOT NULL DEFAULT false,
    deleted_at      timestamptz,
    created_at      timestamptz  NOT NULL,
    updated_at      timestamptz  NOT NULL
);
-- Emails are unique case-insensitively, including soft-deleted accounts (deleted emails stay reserved).
CREATE UNIQUE INDEX ux_users_email ON users (lower(email));
CREATE INDEX ix_users_role ON users (role);
CREATE INDEX ix_users_created_at ON users (created_at);

CREATE TABLE designer_profiles (
    id                   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    designer_id          integer NOT NULL UNIQUE REFERENCES users (id),
    bio                  varchar(2000),
    years_of_experience  integer CHECK (years_of_experience BETWEEN 0 AND 80),
    specialisation       varchar(150),
    created_at           timestamptz NOT NULL,
    updated_at           timestamptz NOT NULL
);

CREATE TABLE stored_files (
    file_key      varchar(64)  PRIMARY KEY,
    content_type  varchar(50)  NOT NULL,
    size_bytes    integer      NOT NULL,
    data          bytea        NOT NULL,
    created_at    timestamptz  NOT NULL
);

CREATE TABLE designer_companies (
    id                   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    designer_id          integer NOT NULL UNIQUE REFERENCES users (id),
    company_name         varchar(150) NOT NULL,
    registration_number  varchar(50),
    description          text,
    address              varchar(255),
    contact_email        varchar(255),
    contact_phone        varchar(30),
    website_url          varchar(255),
    logo_key             varchar(64),
    created_at           timestamptz NOT NULL,
    updated_at           timestamptz NOT NULL
);
CREATE INDEX ix_company_name ON designer_companies (lower(company_name));

CREATE TABLE categories (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         varchar(100) NOT NULL,
    description  varchar(500),
    active       boolean      NOT NULL DEFAULT true,
    created_at   timestamptz  NOT NULL,
    updated_at   timestamptz  NOT NULL
);
CREATE UNIQUE INDEX ux_categories_name ON categories (lower(name));

CREATE TABLE projects (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    designer_id  integer       NOT NULL REFERENCES users (id),
    category_id  integer       NOT NULL REFERENCES categories (id),
    title        varchar(150)  NOT NULL,
    description  text,
    status       varchar(20)   NOT NULL CHECK (status IN ('CURRENT','COMPLETED')),
    budget       numeric(12,2) CHECK (budget >= 0),
    start_date   date,
    end_date     date,
    location     varchar(150),
    deleted      boolean       NOT NULL DEFAULT false,
    deleted_at   timestamptz,
    created_at   timestamptz   NOT NULL,
    updated_at   timestamptz   NOT NULL,
    CONSTRAINT ck_projects_dates CHECK (end_date IS NULL OR start_date IS NULL OR end_date >= start_date)
);
CREATE INDEX ix_projects_designer ON projects (designer_id);
CREATE INDEX ix_projects_category ON projects (category_id);
CREATE INDEX ix_projects_created_at ON projects (created_at);
CREATE INDEX ix_projects_budget ON projects (budget);
CREATE INDEX ix_projects_status ON projects (status);

CREATE TABLE project_images (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id  integer     NOT NULL REFERENCES projects (id),
    file_key    varchar(64) NOT NULL REFERENCES stored_files (file_key),
    sort_order  integer     NOT NULL,
    cover       boolean     NOT NULL DEFAULT false,
    created_at  timestamptz NOT NULL
);
CREATE INDEX ix_project_images_project ON project_images (project_id);

CREATE TABLE favourites (
    customer_id  integer     NOT NULL REFERENCES users (id),
    project_id   integer     NOT NULL REFERENCES projects (id),
    saved_at     timestamptz NOT NULL,
    PRIMARY KEY (customer_id, project_id)
);
CREATE INDEX ix_favourites_project ON favourites (project_id);
CREATE INDEX ix_favourites_saved_at ON favourites (saved_at);

CREATE TABLE project_views (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id   integer     NOT NULL REFERENCES projects (id),
    customer_id  integer     NOT NULL REFERENCES users (id),
    view_date    date        NOT NULL,
    viewed_at    timestamptz NOT NULL,
    CONSTRAINT ux_project_views_daily UNIQUE (customer_id, project_id, view_date)
);
CREATE INDEX ix_project_views_project ON project_views (project_id);
CREATE INDEX ix_project_views_date ON project_views (view_date);

CREATE TABLE enquiries (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id   integer       NOT NULL REFERENCES projects (id),
    customer_id  integer       NOT NULL REFERENCES users (id),
    message      varchar(2000) NOT NULL,
    status       varchar(20)   NOT NULL CHECK (status IN ('NEW','READ','REPLIED')),
    read_at      timestamptz,
    replied_at   timestamptz,
    created_at   timestamptz   NOT NULL,
    updated_at   timestamptz   NOT NULL
);
CREATE INDEX ix_enquiries_project ON enquiries (project_id);
CREATE INDEX ix_enquiries_customer ON enquiries (customer_id);
CREATE INDEX ix_enquiries_created_at ON enquiries (created_at);

CREATE TABLE availability (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    designer_id  integer     NOT NULL REFERENCES users (id),
    calendar_date date       NOT NULL,
    status       varchar(20) NOT NULL CHECK (status IN ('AVAILABLE','UNAVAILABLE')),
    updated_at   timestamptz NOT NULL,
    CONSTRAINT ux_availability_designer_date UNIQUE (designer_id, calendar_date)
);

CREATE TABLE ratings (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id  integer       NOT NULL REFERENCES users (id),
    designer_id  integer       NOT NULL REFERENCES users (id),
    project_id   integer       REFERENCES projects (id),
    score        integer       NOT NULL CHECK (score BETWEEN 1 AND 5),
    comment      varchar(1000),
    created_at   timestamptz   NOT NULL,
    updated_at   timestamptz   NOT NULL
);
-- One general rating per customer per designer (project empty), one rating per customer per project.
CREATE UNIQUE INDEX ux_ratings_general ON ratings (customer_id, designer_id) WHERE project_id IS NULL;
CREATE UNIQUE INDEX ux_ratings_project ON ratings (customer_id, project_id) WHERE project_id IS NOT NULL;
CREATE INDEX ix_ratings_designer ON ratings (designer_id);

CREATE TABLE issue_reports (
    id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_id         integer       NOT NULL REFERENCES users (id),
    type                varchar(30)   NOT NULL CHECK (type IN ('IDP_OR_DESIGNER','PLATFORM_ISSUE')),
    target_project_id   integer       REFERENCES projects (id),
    target_designer_id  integer       REFERENCES users (id),
    title               varchar(150)  NOT NULL,
    description         varchar(2000) NOT NULL,
    status              varchar(20)   NOT NULL CHECK (status IN ('OPEN','RECTIFIED')),
    created_at          timestamptz   NOT NULL,
    rectified_at        timestamptz,
    rectified_by_id     integer       REFERENCES users (id)
);
CREATE INDEX ix_issue_reports_reporter ON issue_reports (reporter_id);
CREATE INDEX ix_issue_reports_status ON issue_reports (status);
CREATE INDEX ix_issue_reports_created_at ON issue_reports (created_at);
